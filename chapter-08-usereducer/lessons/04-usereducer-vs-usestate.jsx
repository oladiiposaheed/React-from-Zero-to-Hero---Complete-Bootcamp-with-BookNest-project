// ==========================================
// LESSON 4: useReducer vs useState
// ==========================================
//
// useState = simple state
//   Counter, text input, toggle
//
// useReducer = complex state
//   Cart, form with validation, game state
//
// RULE OF THUMB:
//   1-2 state updates → useState
//   3+ state updates → useReducer
//   Related updates → useReducer
// ==========================================