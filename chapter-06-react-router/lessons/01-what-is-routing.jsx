// ==========================================
// LESSON 1: What is Routing?
// ==========================================
//
// Routing = showing different content based on URL.
//
// WITHOUT ROUTING:
//   One page, everything visible at once.
//
// WITH ROUTING:
//   /           → Home page
//   /book/3     → Book details for ID 3
//   /cart       → Cart page
//   /anything   → 404 Not Found
//
// React Router = library that handles routing in React.
// SPA = Single Page Application (no full page reload).
// ==========================================